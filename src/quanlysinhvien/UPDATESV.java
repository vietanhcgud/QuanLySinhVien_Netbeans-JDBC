    public void HienthiSQL() {
        for (SINHVIEN s : list) {
            model.addRow(new Object[]{
                i++, s.getMASV(), s.getHOSV(), s.getTENSV(), s.getGT(), s.getNS(), s.getLOP(), s.getMAKHOA()
            });
        }       
    }
    public void Hienthi() {
        i = 1;
        model.setRowCount(0);
        for (SINHVIEN s : list) {
            model.addRow(new Object[]{
                i++, s.getMASV(), s.getHOSV(), s.getTENSV(), s.getGT(), s.getNS(), s.getLOP(), s.getMAKHOA()
            });
        }       
    }

