    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        selectedSV = tblDSSV.getSelectedRow();
        if(list.size() == 0) {
            JOptionPane.showMessageDialog(rootPane,
                    "Không có sinh viên để sửa!");
        }
        else if (selectedSV == -1) {
            JOptionPane.showMessageDialog(rootPane,
                    "Hãy chọn một sinh viên để sửa!");
        }
        else {
            SUASV sua = new SUASV(this, rootPaneCheckingEnabled);
            sua.setEditData(list.get(selectedSV));
            sua.setVisible(true);
            Hienthi();
        }
    }//GEN-LAST:event_btnSuaActionPerformed

