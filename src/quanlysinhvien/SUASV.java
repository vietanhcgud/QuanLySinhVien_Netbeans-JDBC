    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        SINHVIEN s = new SINHVIEN();
        s.setMASV(txtMASV.getText());
        s.setHOSV(txtHOSV.getText());
        s.setTENSV(txtTENSV.getText());
        s.setGT(txtGT.getText());
        s.setNS(txtNS.getText());
        s.setLOP(txtLOP.getText());
        s.setMAKHOA(txtMAKHOA.getText());
        
        if(new JVC().editSV(s)) {
            JOptionPane.showMessageDialog(parents, "Sửa thành công!");
            parents.Hienthi();
            parents.list.remove(parents.list.get(parents.selectedSV));
            parents.list.add(s);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(parents, "Thông tin định dạng sai mời bạn nhập lại!");
        }
    }//GEN-LAST:event_btnSuaActionPerformed

